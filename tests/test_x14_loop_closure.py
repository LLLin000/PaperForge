def test_facet_vocabulary_covers_the_probe_source() -> None:
    """A new literal state in a lineage probe must force a contract update."""
    from paperforge.reconcile import FACET_STATES

    probe_literals = _probe_function_return_literals(
        ROOT / "paperforge" / "lineage.py",
        {"_probe_ocr_state", "_probe_retrieval_state", "_probe_vector_state"},
    )
    assert {"current", "stale", "missing", "unknown"} <= probe_literals
    # Every literal is a real facet state for at least one layer.
    known = {state for states in FACET_STATES.values() for state in states}
    assert probe_literals <= known, probe_literals - known


def _facet_observation(layer: str, state: str):
    """A PaperObservation isolating one layer's state; other layers current."""
    from paperforge.reconcile import PaperObservation

    base = {"ocr": "current", "retrieval": "current", "vector": "current"}
    base[layer] = state
    return PaperObservation(
        key="KEY1",
        ocr=base["ocr"],
        retrieval=base["retrieval"],
        vector=base["vector"],
        identities={},
        details=None,
    )


def test_every_facet_state_closes_to_action_or_no_action() -> None:
    """Each declared state maps ONLY to its declared actions (or none) — the
    X14 closure property.  A state that quietly emitted an undeclared action
    (or a repairable state that emitted nothing) fails here."""
    from paperforge.reconcile import (
        FACET_REPAIR_ACTIONS,
        FACET_STATES,
        _per_paper_intents,
    )

    for layer, states in FACET_STATES.items():
        for state in states:
            declared = set(FACET_REPAIR_ACTIONS.get((layer, state), ()))
            emitted = {
                intent.action_id for intent in _per_paper_intents(_facet_observation(layer, state))
            }
            assert emitted <= declared, (layer, state, emitted, declared)
            if declared:
                # A repairable state must actually repair — no dead mapping.
                assert emitted, (layer, state, "declared repair never emitted")


def test_unknown_facet_states_emit_no_intent() -> None:
    """``unknown`` is a first-class fail-closed state: no intent, never
    interpreted as stale (design §2.3).  The reconcile-level reason string is
    asserted in tests/test_reconcile.py::TestMinimalFrontier."""
    from paperforge.reconcile import FACET_NO_ACTION, _per_paper_intents

    for layer in ("ocr", "retrieval", "vector"):
        assert (layer, "unknown") in FACET_NO_ACTION
        assert _per_paper_intents(_facet_observation(layer, "unknown")) == []


def test_uncontracted_facet_state_is_surfaced(monkeypatch, tmp_path: Path) -> None:
    """Fail closed: a facet state outside the contract is reported, not
    dropped — otherwise a new probe state would pass in silence."""
    import paperforge.reconcile as reconcile_module
    from paperforge.reconcile import PaperObservation, reconcile

    bogus = PaperObservation(
        key="KEY1", ocr="bogus_state", retrieval="current", vector="current",
        identities={}, details=None,
    )
    monkeypatch.setattr(
        reconcile_module,
        "observe",
        lambda vault, keys=None: reconcile_module.ReconcileObservation(
            global_state=reconcile_module.GlobalObservation(
                memory_substrate_ok=True, vector_substrate_ok=True
            ),
            papers=(bogus,),
            vault=vault,
        ),
    )
    # No intents are emitted (no contract key), so the gateway only needs the
    # (empty) last-attempt read; the vault itself is never touched.
    monkeypatch.setattr(reconcile_module, "read_last_attempts", lambda vault: {})
    result = reconcile(tmp_path)
    assert "reconcile.facet_uncontracted:KEY1:ocr:bogus_state" in result.data["diagnostics"]


# ── (d) direct `action run` settles the same W2 attempt ───────────────────


def test_direct_action_run_settles_the_chain_w2_record(synced_copy) -> None:
    """Gap: the W2 attempt was written only by the chain; a direct
    ``action run`` bypassed it.  Now it settles the same record the chain
    computes (`semantic_attempt_digest`), so the reconcile gate consumes it."""
    vault, home = synced_copy
    result = _pf(
        vault, home,
        "action", "run", "ocr.rebuild_derived",
        "--scope", "papers", "--key", KEY, "--json",
    )
    assert result.returncode == 0, result.stdout[-2000:] + result.stderr[-2000:]

    from paperforge.reconcile import read_last_attempts, semantic_attempt_digest

    attempts = read_last_attempts(vault)
    record = attempts.get(f"ocr.rebuild_derived:papers:{KEY}")
    assert record is not None, attempts
    assert record["outcome"] == "succeeded"
    # Same digest the chain path records for this very intent.
    chain_digest = semantic_attempt_digest(
        vault,
        {"action_id": "ocr.rebuild_derived", "scope": {"kind": "papers", "keys": [KEY]}},
    )
    assert record["input_digest"] == chain_digest


def test_predispatch_failure_settles_nothing(synced_copy) -> None:
    """Only a DISPATCHED attempt settles: rc3 (confirmation required) is not a
    failed attempt and must not create a record."""
    vault, home = synced_copy
    result = _pf(vault, home, "action", "run", "memory.build", "--json")
    assert result.returncode == 3, result.stdout[-1500:] + result.stderr[-1500:]

    from paperforge.reconcile import read_last_attempts

    assert read_last_attempts(vault) == {}
