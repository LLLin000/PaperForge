"""X14 — observation→action loop closure (acceptance plan §5, case X14).

X14: every fact a probe/lineage report emits must either (a) resolve to a
registered, dispatchable action, or (b) carry a written no-action contract;
every action id sent outward must be in the registry; and no rule may be
unable to fail.

This file grounds the *closure* end to end, complementing (not repeating) the
per-gap tests:

- **probe ids** — enumerated statically from ``commands/probe.py`` AND from
  real ``probe <module> --json`` runs on the e2e fixture vault; each must be
  registered or a declared non-registry (UI-only) action.  The product-side
  table and construction guard are #223 (tests/test_action_registry.py); this
  file proves *source + live* enumeration against it.
- **facet states** — every per-paper facet state the lineage probe reports,
  including ``unknown``, must map to a registered action or an explicit
  no-action contract (``reconcile.FACET_STATES`` / ``FACET_REPAIR_ACTIONS`` /
  ``FACET_NO_ACTION``).
- **unfailable rule** — #220; already covered by
  ``tests/test_architecture_audit_reconcile.py::TestRuleSubjectBinding``
  (``test_unbound_subject_is_not_satisfied`` and
  ``test_unbound_subject_makes_the_audit_ineligible``), so it is referenced,
  never re-implemented here.
- **W2 attempt** — a direct ``paperforge action run`` of an automatic action
  settles the same overwrite-only last-attempt record as the follow-up chain,
  so the reconcile re-emission gate cannot be bypassed by skipping the chain.
"""

