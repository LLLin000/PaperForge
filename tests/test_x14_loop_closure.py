# ── (a) probe action ids ──────────────────────────────────────────────────


def _static_probe_action_ids() -> set[str]:
    """Every ``action_id`` the probe can place in an envelope, from source.

    Reads the keyword arguments of the product's own ``build_action_primary``
    calls — no hand-maintained list — and expands the one dynamic id
    (``f"{mod_name}.probe"`` over ``PROBE_ORDER``).
    """
    tree = ast.parse(PROBE_SOURCE.read_text(encoding="utf-8"))
    ids: set[str] = set()
    dynamic: list[str] = []
    for node in ast.walk(tree):
        if not (isinstance(node, ast.keyword) and node.arg == "action_id"):
            continue
        value = node.value
        if isinstance(value, ast.Constant) and isinstance(value.value, str):
            ids.add(value.value)
        elif isinstance(value, ast.IfExp):
            for branch in (value.body, value.orelse):
                assert isinstance(branch, ast.Constant) and isinstance(branch.value, str)
                ids.add(branch.value)
        elif isinstance(value, ast.JoinedStr):
            parts: list[str] = []
            for piece in value.values:
                if isinstance(piece, ast.Constant):
                    parts.append(str(piece.value))
                elif isinstance(piece, ast.FormattedValue) and isinstance(
                    piece.value, ast.Name
                ):
                    parts.append("{" + piece.value.id + "}")
                else:  # pragma: no cover - guards a new dynamic shape
                    raise AssertionError(f"unhandled probe action_id piece: {ast.dump(piece)}")
            dynamic.append("".join(parts))
        else:  # pragma: no cover - guards a new dynamic shape
            raise AssertionError(f"unhandled probe action_id expr: {ast.dump(value)}")
    for expr in dynamic:
        assert expr == "{mod_name}.probe", f"new dynamic probe id: {expr!r}"
        ids |= {f"{stem}.probe" for stem in PROBE_ORDER_STEMS}
    assert ids, "static probe enumeration found no action ids"
    return ids


def _unclassified_action_ids(action_ids: Iterable[str]) -> list[str]:
    """Ids nothing can execute: neither registered nor a declared non-registry
    (UI-only) action.  Non-empty means a dead control reached a user."""
    from paperforge.actions.registry import ACTION_REGISTRY, NON_REGISTRY_ACTIONS

    executable = set(ACTION_REGISTRY) | set(NON_REGISTRY_ACTIONS)
    return sorted(set(action_ids) - executable)


def _live_probe_action_ids(vault: Path, home: Path) -> set[str]:
    """Every ``action_id`` a real ``probe <module> --json`` envelope emits."""
    found: set[str] = set()
    for module in PROBE_MODULES:
        result = _pf(vault, home, "probe", module, "--json")
        assert result.returncode == 0, (module, result.stderr[-1500:])
        envelope = json.loads(result.stdout)

        def walk(obj: object) -> None:
            if isinstance(obj, dict):
                if isinstance(obj.get("action_id"), str):
                    found.add(obj["action_id"])
                for value in obj.values():
                    walk(value)
            elif isinstance(obj, list):
                for value in obj:
                    walk(value)

        walk(envelope)
    return found


def test_every_static_probe_action_id_is_executable() -> None:
    static = _static_probe_action_ids()
    assert _unclassified_action_ids(static) == []


def test_every_live_probe_action_id_is_executable(built_vault: Path, tmp_path: Path) -> None:
    home = tmp_path / "home"
    home.mkdir()
    live = _live_probe_action_ids(built_vault, home)
    assert live, "no probe module advertised an action id"
    assert _unclassified_action_ids(live) == []
    # The live ids are a subset of the static enumeration — the static gate
    # above therefore covers whatever a real run can emit.
    assert live <= _static_probe_action_ids(), live - _static_probe_action_ids()


def test_unregistered_action_id_is_refused() -> None:
    """Negative control: the checker fails on an id nothing can dispatch."""
    from paperforge.actions.registry import UnknownActionId, classify_action_id

    bogus = "not.a.real.probe.action"
    assert _unclassified_action_ids([bogus]) == [bogus]
    with pytest.raises(UnknownActionId):
        classify_action_id(bogus)


# ── (a′) reconcile's own outward action ids ───────────────────────────────


def _static_reconcile_action_ids() -> set[str]:
    """Every ``ActionIntent(action_id=...)`` literal reconcile can emit."""
    tree = ast.parse(RECONCILE_SOURCE.read_text(encoding="utf-8"))
    ids: set[str] = set()
    for node in ast.walk(tree):
        if not (isinstance(node, ast.keyword) and node.arg == "action_id"):
            continue
        value = node.value
        if isinstance(value, ast.Constant) and isinstance(value.value, str):
            ids.add(value.value)
        else:
            # The only non-literal is the digest helper re-wrapping its own
            # ``action_id`` parameter — never an emitted id.
            assert isinstance(value, ast.Name) and value.id == "action_id", ast.dump(value)
    assert ids
    return ids


def test_reconcile_emits_only_the_declared_actions() -> None:
    """The W2 direct-run gate keys off RECONCILE_ACTIONS — it must equal the
    ids reconcile actually emits, and every one must be registered."""
    from paperforge.actions.registry import ACTION_REGISTRY
    from paperforge.reconcile import RECONCILE_ACTIONS

    emitted = _static_reconcile_action_ids()
    assert emitted == set(RECONCILE_ACTIONS), (emitted, set(RECONCILE_ACTIONS))
    assert _unclassified_action_ids(emitted) == []
    assert emitted <= set(ACTION_REGISTRY)


# ── (b) facet-state closure ───────────────────────────────────────────────


def _probe_function_return_literals(module: Path, names: set[str]) -> set[str]:
    """String literals returned by the named functions (lineage state probes).

    A partial static grounding only: the ocr values assembled from
    ``top_state``/``identity_state`` variables are covered by FACET_STATES.
    """
    tree = ast.parse(module.read_text(encoding="utf-8"))
    found: set[str] = set()
    for fn in ast.walk(tree):
        if not (isinstance(fn, ast.FunctionDef) and fn.name in names):
            continue
        for node in ast.walk(fn):
            if (
                isinstance(node, ast.Return)
                and isinstance(node.value, ast.Constant)
                and isinstance(node.value.value, str)
            ):
                found.add(node.value.value)
    return found


