# ── fixtures ──────────────────────────────────────────────────────────────


def _env(home: Path) -> dict[str, str]:
    env = dict(os.environ)
    env.update(
        HOME=str(home),
        USERPROFILE=str(home),
        PYTHONIOENCODING="utf-8",
        PYTHON_KEYRING_BACKEND="keyring.backends.null.Keyring",
    )
    for name in list(env):
        if name.startswith("PAPERFORGE_CREDENTIAL_"):
            env.pop(name)
    return env


def _pf(vault: Path, home: Path, *args: str) -> subprocess.CompletedProcess[str]:
    return subprocess.run(
        [sys.executable, "-m", "paperforge", "--vault", str(vault), *args],
        capture_output=True,
        text=True,
        encoding="utf-8",
        errors="replace",
        env=_env(home),
        timeout=170,
    )


