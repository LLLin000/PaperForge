"""X13 — queries are read-only (acceptance plan §5, issue #265; #221/#226/#228).

Every entry declared as a read/report runs as a REAL ``python -m paperforge``
subprocess against a synced copy of the e2e fixture vault, and the vault must
be byte-identical afterwards: no file created, deleted or changed.

The only tolerated churn is mtime-only touches of SQLite's shared-memory /
WAL files and the read-lock file that a reader takes; their *content* may not
change and they may not be created by a read.

Edge states are covered too (a user-edited Base view, a missing logs dir, a
missing memory DB, no Bases dir), because the historical writes (#221: status
rewrote ``.base``; dashboard/runtime-health created probe dirs) only fired
when the vault was not in its steady state.

``render audit`` is declared as a writer of its own report (``cli.py`` help,
``docs/COMMANDS.md``) and is asserted to write exactly that file and nothing
else. A mutating control (``base-refresh`` on an edited Base) proves the
detector can fail — X13 requires the gate to be triggerable.
"""

