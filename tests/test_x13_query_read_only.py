@pytest.fixture
def prepare(tmp_path: Path, built_vault: Path):
    def _do(state: str) -> tuple[Path, Path]:
        return _prepare(tmp_path, built_vault, state)

    return _do


def _prepare(tmp_path: Path, source: Path, state: str) -> tuple[Path, Path]:
    vault = tmp_path / "vault"
    home = tmp_path / "home"
    home.mkdir()
    shutil.copytree(source, vault)
    synced = _pf(vault, home, "sync", "--json")
    assert synced.returncode == 0, synced.stdout[-2000:] + synced.stderr[-2000:]
    if state == "edited_base":
        bases = sorted((vault / "Bases").glob("*.base"))
        assert bases, "fixture guard: the e2e vault must ship Base views"
        for base in bases:
            base.write_text(
                base.read_text(encoding="utf-8") + "\n# user edit (X13)\n", encoding="utf-8"
            )
    elif state == "no_logs":
        shutil.rmtree(vault / "System" / "PaperForge" / "logs", ignore_errors=True)
    elif state == "no_memory_db":
        dbs = list((vault / "System" / "PaperForge" / "indexes").glob("paperforge.db*"))
        assert dbs, "fixture guard: sync must have built the memory DB"
        for db in dbs:
            db.unlink()
    elif state == "no_bases":
        shutil.rmtree(vault / "Bases")
    else:
        assert state == "steady", state
    return vault, home


def _assert_reads_do_not_write(vault: Path, home: Path, commands: list[list[str]]) -> None:
    offenders: list[str] = []
    for args in commands:
        before = _snapshot(vault)
        result = _pf(vault, home, *args)
        after = _snapshot(vault)
        # Exit 0/1 are reports (doctor fails checks with 1); 2 is a usage error,
        # which would make this case vacuous.
        assert result.returncode in (0, 1), (args, result.returncode, result.stderr[-1500:])
        writes = _durable_writes(before, after)
        if writes:
            offenders.append(f"paperforge {' '.join(args)}: {writes[:8]}")
    assert not offenders, "read/report entries wrote to the vault:\n" + "\n".join(offenders)


@pytest.mark.timeout(900)
def test_read_entries_leave_a_steady_vault_byte_identical(prepare) -> None:
    vault, home = prepare("steady")
    _assert_reads_do_not_write(vault, home, READ_COMMANDS)


@pytest.mark.timeout(600)
@pytest.mark.parametrize("state", ["edited_base", "no_logs", "no_memory_db", "no_bases"])
def test_read_entries_do_not_repair_edge_states(prepare, state: str) -> None:
    vault, home = prepare(state)
    _assert_reads_do_not_write(vault, home, EDGE_COMMANDS)


@pytest.mark.timeout(300)
def test_render_audit_writes_only_its_declared_report(prepare) -> None:
    vault, home = prepare("steady")
    report = f"System/PaperForge/ocr/{KEY}/render/render.consistency.json"
    (vault / report).unlink(missing_ok=True)
    before = _snapshot(vault)
    result = _pf(vault, home, "render", "audit", KEY, "--json")
    assert result.returncode in (0, 1), result.stderr[-1500:]
    writes = _durable_writes(before, _snapshot(vault))
    assert writes == [f"created {report}"], writes


@pytest.mark.timeout(300)
def test_detector_fails_on_a_real_write(prepare) -> None:
    # Negative control: a mutating verb on an edited Base view MUST be caught,
    # otherwise the read-only assertions above could pass vacuously.
    vault, home = prepare("edited_base")
    before = _snapshot(vault)
    result = _pf(vault, home, "base-refresh", "--force")
    assert result.returncode == 0, result.stderr[-1500:]
    writes = _durable_writes(before, _snapshot(vault))
    assert any(w.startswith("changed Bases/") for w in writes), writes
