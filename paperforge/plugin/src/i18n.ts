export const I18N_DICTIONARIES = LANG;

let T: Record<string, string> | null = null;

export function langFromApp(app: App): "zh" | "en" {
  try {
    const vault = app.vault as unknown as Record<string, unknown>;
    if (typeof vault.getConfig === "function") {
      const l = vault.getConfig("language") as string;
      if (l && String(l).startsWith("zh")) return "zh";
    }
  } catch {}
  try {
    if (typeof localStorage !== "undefined") {
      const l = localStorage.getItem("language");
      if (l && String(l).startsWith("zh")) return "zh";
    }
  } catch {}
  try {
    const language = document.documentElement.lang || navigator.language;
    if (language && language.startsWith("zh")) return "zh";
  } catch {}
  return "en";
}

export function setLanguage(app: App, override = ""): void {
  const language = override || langFromApp(app);
  T = language.startsWith("zh") ? LANG.zh : LANG.en;
}

export function getActiveLang(app?: App): "zh" | "en" {
  if (T === LANG.zh) return "zh";
  if (T === LANG.en) return "en";
  return app ? langFromApp(app) : "en";
}

export function t(key: string): string {
  return (T && T[key]) || LANG.en[key] || key;
}
